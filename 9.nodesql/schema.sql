CREATE OR REPLACE PROCEDURE insert_comments_simple (
    p_json IN CLOB
) AS
BEGIN
    -- This loops through the JSON array directly
    FOR rec IN (
        SELECT post_id, user_name, comment_text
        FROM JSON_TABLE(p_json, '$[*]'
            COLUMNS (
                post_id      NUMBER         PATH '$.postId',
                user_name    VARCHAR2(50)   PATH '$.userName',
                comment_text VARCHAR2(4000) PATH '$.text'
            )
        )
    ) LOOP
        -- Inserts each item inside the loop
        INSERT INTO comments (post_id, user_name, comment_text)
        VALUES (rec.post_id, rec.user_name, rec.comment_text);
    END LOOP;
    
    -- Add this line to permanently save the loop data to the table
    COMMIT; 
END; 
