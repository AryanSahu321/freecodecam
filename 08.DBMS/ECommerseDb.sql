CREATE TABLE Address (
    aid NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    city VARCHAR2(100) NOT NULL,
    state VARCHAR2(100) NOT NULL,
    country VARCHAR2(100) NOT NULL,
    user_id NUMBER NOT NULL,
    CONSTRAINT fk_address_user 
        FOREIGN KEY (user_id) REFERENCES UserTable(user_id)
);


CREATE TABLE OrderTable (
    order_no NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_date DATE DEFAULT SYSDATE NOT NULL,
    order_amount NUMBER(10,2) NOT NULL,
    user_id NUMBER NOT NULL,
    CONSTRAINT fk_order_user 
        FOREIGN KEY (user_id) REFERENCES UserTable(user_id)
);


CREATE TABLE Payment (
    pid NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    method VARCHAR2(50) NOT NULL, -- e.g., 'Credit Card', 'PayPal'
    amount NUMBER(10,2) NOT NULL,
    order_no NUMBER NOT NULL,
    CONSTRAINT fk_payment_order 
        FOREIGN KEY (order_no) REFERENCES OrderTable(order_no)
);

CREATE TABLE TrackingDetails (
    order_no NUMBER PRIMARY KEY,
    user_id NUMBER NOT NULL,
    status VARCHAR2(100) NOT NULL, -- e.g., 'Shipped', 'Delivered'
    CONSTRAINT fk_tracking_order 
        FOREIGN KEY (order_no) REFERENCES OrderTable(order_no),
    CONSTRAINT fk_tracking_user 
        FOREIGN KEY (user_id) REFERENCES UserTable(user_id)
);


