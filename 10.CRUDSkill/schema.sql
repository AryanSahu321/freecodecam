-- schema.sql
-- Table definition for Civic Complaints following the Oracle SQL schema

CREATE TABLE complaints (
    complaint_id   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_name      VARCHAR2(50) NOT NULL,
    complaint_text VARCHAR2(4000) NOT NULL,
    created_at     TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- PL/SQL procedure utilizing JSON_TABLE to unpack and insert complaints in bulk[cite: 1]
CREATE OR REPLACE PROCEDURE insert_complaints_simple (
    p_json IN CLOB
) AS 
BEGIN
    FOR rec IN (
        SELECT user_name, complaint_text
        FROM JSON_TABLE(p_json, '$[*]'
            COLUMNS (
                user_name      VARCHAR2(50)   PATH '$.userName',
                complaint_text VARCHAR2(4000) PATH '$.text'
            )
        )
    ) LOOP
        INSERT INTO complaints (user_name, complaint_text)
        VALUES (rec.user_name, rec.complaint_text);
    END LOOP;
    
    COMMIT;
END;
/

select * from complaints;